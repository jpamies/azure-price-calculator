#!/usr/bin/env python3
"""Reduce `az vm list-skus --resource-type virtualMachines --all -o json` to the vm-skus.base.json format.

    az vm list-skus --resource-type virtualMachines --all -o json \
        | python3 scripts/reduce_vm_skus.py > pipeline/data/vm-skus.base.json

Each size appears once per location in the az output; the first entry with vCPUs and MemoryGB
capabilities wins. family "standardDSv5Family" becomes "DSv5".
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


def _number(value: object) -> int | float | None:
    try:
        number = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return None
    return int(number) if number.is_integer() else number


def short_family(family: str) -> str:
    """"standardDSv5Family" -> "DSv5"."""
    short = re.sub(r"family$", "", re.sub(r"^standard", "", family, flags=re.IGNORECASE), flags=re.IGNORECASE)
    return short or family


def reduce_skus(items: list[dict]) -> dict[str, dict]:
    skus: dict[str, dict] = {}
    for item in items:
        if not isinstance(item, dict) or item.get("resourceType", "virtualMachines") != "virtualMachines":
            continue
        name = item.get("name")
        if not name or name in skus:
            continue
        capabilities = {c.get("name"): c.get("value") for c in item.get("capabilities") or [] if isinstance(c, dict)}
        vcpus, memory = _number(capabilities.get("vCPUs")), _number(capabilities.get("MemoryGB"))
        if vcpus is None or memory is None:
            continue
        spec: dict[str, object] = {"vCPUs": vcpus, "memoryGB": memory}
        family = short_family(str(item.get("family") or ""))
        if family:
            spec["family"] = family
        skus[name] = spec
    return dict(sorted(skus.items()))


def render(source: str, note: str, skus: dict[str, dict]) -> str:
    """Same layout as scripts/seed_vm_skus.py: one SKU per line, keys sorted."""
    lines = [f'  {json.dumps(name)}: {json.dumps(spec)}' for name, spec in skus.items()]
    return (
        "{\n"
        f'  "source": {json.dumps(source)},\n'
        f'  "note": {json.dumps(note)},\n'
        '  "skus": {\n  ' + ",\n  ".join(lines) + "\n  }\n}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Reduce az vm list-skus JSON to vm-skus.base.json")
    parser.add_argument("input", nargs="?", type=Path, help="az JSON file (default: stdin)")
    parser.add_argument("-o", "--out", type=Path, help="output file (default: stdout)")
    args = parser.parse_args(argv)
    raw = args.input.read_text(encoding="utf-8") if args.input else sys.stdin.read()
    items = json.loads(raw)
    if not isinstance(items, list):
        parser.error("expected a JSON array (az vm list-skus -o json)")
    skus = reduce_skus(items)
    if not skus:
        parser.error("no virtualMachines SKUs with vCPUs/MemoryGB found in the input")
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    text = render("az-cli", f"Generated by scripts/export-vm-skus.sh (az vm list-skus) on {today}", skus)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out} ({len(skus)} SKUs)", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
